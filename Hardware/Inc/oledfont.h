/* ================== 汉字查找 (支持UTF-8和GB2312) ================== */
static inline uint8_t GetHzIndex(char *str)
{
    uint8_t *s = (uint8_t*)str;
    
    // UTF-8 三字节字符 (汉字)
    if ((*s & 0xF0) == 0xE0)
    {
        for (uint8_t i = 0; HzIndex[i].ch[0] != 0; i++)
        {
            uint8_t *h = (uint8_t*)HzIndex[i].ch;
            if ((*h & 0xF0) == 0xE0) // UTF-8 索引
            {
                if (s[0] == h[0] && s[1] == h[1] && s[2] == h[2])
                    return HzIndex[i].index;
            }
        }
    }
    // GB2312 双字节字符
    else if ((*s & 0x80) != 0)
    {
        for (uint8_t i = 0; HzIndex[i].ch[0] != 0; i++)
        {
            uint8_t *h = (uint8_t*)HzIndex[i].ch;
            if (((*h & 0xF0) != 0xE0) && (*h & 0x80) != 0) // GB2312 索引
            {
                if (s[0] == h[0] && s[1] == h[1])
                    return HzIndex[i].index;
            }
        }
    }
    return 0xFF;
}


