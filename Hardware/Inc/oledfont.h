/* ================================================================================
 * OLED 字模/图形数据表（纯数据头文件，不含可执行逻辑，数组内容一律不要改动）
 * ================================================================================
 * 本文件被 Hardware/Src/oled.c 直接包含，供其绘制函数取模。表里所有数据都是
 * "给 ST7565/AiP31567 系单色 128x64 屏"用的字节点阵，与 oled.c 的页地址模式
 * 严格对应：一个字节 = 一列上的 8 个纵向像素，bit7 在上、bit0 在下。
 *
 * 【取模方式】汉字与 ASCII 均为"纵向取模、字节正序、高位在上（MSB first）"，
 *   即从字形左上角开始，沿列自上而下取 8 位组成 1 字节，再向右一列继续。
 *   PC 端取模软件（如 PCtoLCD2002）请按"阴码、逐列式、顺向、高位在前"设置，
 *   否则字会上下颠倒或左右镜像。
 *
 * 【四张表】
 *  1) Hzk[][24] —— 汉字 12x12 点阵，每个汉字 24 字节 = 2 页 × 12 字节：
 *       下标 0~11   → 上半部 12 列（画在第 page 页）
 *       下标 12~23  → 下半部 12 列（画在第 page+1 页）
 *     纵向只有 12 行，因而下半部只用到每页字节的低 4 位。
 *     数组尾部有若干空槽（如下标 186、187、0xFF 对应项为空 {}），属预留。
 *  2) HzIndex[] —— 汉字索引表，元素为 {字符编码, Hzk 下标}。
 *     配套 GetHzIndex() 按字符串的真实编码在表中匹配：
 *       首字节 & 0xF0 == 0xE0 → UTF-8 三字节汉字，逐 3 字节比较；
 *       首字节 & 0x80 != 0     → GB2312 双字节汉字，逐 2 字节比较；
 *       都不是                 → ASCII，不要调用本表。
 *     匹配不到时返回 0xFF，调用方（oled.c）据此跳过不画。
 *     注意："D/K/d/m/n/g/l/i/s/h/F/r/a/E/?" 等条目存的是英文单字母，
 *     它们与汉字不同，是单字节，供个别界面按 GB2312 分支匹配时使用，
 *     新增字符时须保证 ch[3] 里的编码格式与查找分支一致。
 *  3) ASCIIchardot[95][12] —— ASCII 8x16 点阵，下标 = 字符码 - 0x20
 *     （即 0x20 空格 对应下标 0，0x7E '~' 对应下标 94）。
 *     前 6 字节为上半部 6 列、后 6 字节为下半部 6 列，
 *     被 LCD_ShowChar / LCD_ShowCharCompact / LCD_ShowCharReverse 使用。
 *  4) F6x8[][6] —— ASCII 6x8 小点阵，下标 = 字符码 - 0x20（' ' 空格 = 0）。
 *     每个字符仅 6 列、单页高，被 LCD_ShowStr_Small / ..._Compact 使用。
 *     ★本表只有数字 0~9、常用符号以及 d/m/n 填了数据，
 *       字母、大写字母等表项是空的 {}（会显示为空白），
 *       不是数据缺失的 bug，而是在此屏上从不使用这些字符以省 Flash。
 *       如需显示某个字母，必须补上它那 6 个字节。
 *
 * 【如何新增一个汉字】
 *   ① 用取模软件按上述方式生成 24 字节 12x12 数据；
 *   ② 在 Hzk[] 末尾（空槽之前）追加一条 { 0x.., ... }，并记下它的下标 N；
 *   ③ 在 HzIndex[] 的终止项 {"", 0xFF} 之前追加 {"新字", N}，
 *      注意 HzIndex[].ch[3] 上限 3 字节：UTF-8 汉字正好占满 3 字节，
 *      GB2312 占 2 字节 + 结束符；
 *   ④ 源文件必须保存为 UTF-8 编码，否则 UTF-8 分支的逐字节比较会失配。
 * ================================================================================ */

